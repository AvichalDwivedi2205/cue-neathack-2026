import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";
import { agentId, taskState, taskAction } from "./workspaceValidators";
import { growthTables } from "./growthSchema";
import { prospectTables } from "./prospectSchema";

export default defineSchema({
  ...growthTables,
  ...prospectTables,
  agentConversations: defineTable({
    appId: v.string(),
    agent: agentId,
    participant: v.string(),
    threadId: v.string(),
    createdAt: v.number(),
  }).index("by_appId_and_agent_and_participant", [
    "appId",
    "agent",
    "participant",
  ]),
  agentCommands: defineTable({
    key: v.string(),
    conversationId: v.id("agentConversations"),
    actor: v.string(),
    via: v.string(),
    taskId: v.optional(v.id("agentTasks")),
    contextTask: v.optional(v.string()),
    promptId: v.string(),
    replyId: v.string(),
    response: v.string(),
    promptText: v.string(),
    requestContext: v.optional(v.string()),
    answerStatus: v.optional(
      v.union(v.literal("queued"), v.literal("completed"), v.literal("failed")),
    ),
    answerLease: v.optional(v.string()),
    answerLeaseUntil: v.optional(v.number()),
    createdAt: v.number(),
  })
    .index("by_key", ["key"])
    .index("by_conversationId", ["conversationId"]),
  agentTasks: defineTable({
    appId: v.string(),
    agent: agentId,
    action: taskAction,
    key: v.string(),
    title: v.string(),
    state: taskState,
    stage: v.string(),
    issueId: v.optional(v.id("issues")),
    runId: v.optional(v.id("runs")),
    opportunityId: v.optional(v.id("growthOpportunities")),
    campaignId: v.optional(v.id("growthCampaigns")),
    parentId: v.optional(v.id("agentTasks")),
    dependencies: v.optional(v.array(v.string())),
    reviewer: v.optional(v.string()),
    blocker: v.optional(v.string()),
    workId: v.optional(v.string()),
    leaseToken: v.optional(v.string()),
    leaseUntil: v.optional(v.number()),
    attempts: v.number(),
    cancel: v.boolean(),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("by_key", ["key"])
    .index("by_appId", ["appId"]),
  agentTaskEvents: defineTable({
    taskId: v.id("agentTasks"),
    actor: v.string(),
    kind: v.string(),
    text: v.string(),
    createdAt: v.number(),
    evidence: v.optional(v.string()),
  }).index("by_taskId", ["taskId"]),
  agentSlackThreads: defineTable({
    key: v.string(),
    appId: v.string(),
    agent: agentId,
    taskId: v.optional(v.id("agentTasks")),
    participant: v.string(),
  }).index("by_key", ["key"]),
  serverState: defineTable({
    key: v.string(),
    value: v.string(),
    version: v.number(),
    updatedAt: v.number(),
  }).index("by_key", ["key"]),
  triageReceipts: defineTable({
    caseId: v.id("cases"),
    messageId: v.id("messages"),
    status: v.union(
      v.literal("queued"),
      v.literal("completed"),
      v.literal("superseded"),
      v.literal("failed"),
    ),
    workId: v.optional(v.string()),
    updatedAt: v.number(),
  }).index("by_messageId", ["messageId"]),
  backgroundLeases: defineTable({
    name: v.literal("x"),
    token: v.string(),
    until: v.number(),
  }).index("by_name", ["name"]),
  cases: defineTable({
    title: v.string(),
    customer: v.string(),
    initials: v.string(),
    channel: v.string(),
    appId: v.optional(v.string()),
    externalId: v.optional(v.string()),
    body: v.string(),
    status: v.string(),
    priority: v.string(),
    issueId: v.optional(v.id("issues")),
    tags: v.array(v.string()),
    sourceUrl: v.optional(v.string()),
    provenance: v.string(),
    owner: v.optional(v.string()),
    sourceKey: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("by_updatedAt", ["updatedAt"])
    .index("by_sourceKey", ["sourceKey"])
    .index("by_issueId", ["issueId"])
    .index("by_owner", ["owner"]),
  issues: defineTable({
    title: v.string(),
    description: v.string(),
    kind: v.string(),
    fingerprint: v.string(),
    appId: v.optional(v.string()),
    status: v.string(),
    priority: v.string(),
    tags: v.array(v.string()),
    createdAt: v.number(),
    spec: v.optional(v.string()),
    specApprovedAt: v.optional(v.number()),
    specApprovedBy: v.optional(v.string()),
  }).index("by_fingerprint", ["fingerprint"]),
  messages: defineTable({
    caseId: v.id("cases"),
    author: v.string(),
    role: v.string(),
    body: v.string(),
    createdAt: v.number(),
  })
    .index("by_caseId_and_createdAt", ["caseId", "createdAt"])
    .index("by_caseId_and_role_and_createdAt", ["caseId", "role", "createdAt"]),
  runs: defineTable({
    issueId: v.id("issues"),
    status: v.string(),
    phase: v.string(),
    provider: v.string(),
    createdAt: v.number(),
    updatedAt: v.number(),
    rootCause: v.optional(v.string()),
    diff: v.optional(v.string()),
    before: v.optional(v.string()),
    after: v.optional(v.string()),
    prUrl: v.optional(v.string()),
    commit: v.optional(v.string()),
    repoPath: v.optional(v.string()),
    error: v.optional(v.string()),
    deployed: v.optional(v.boolean()),
    verified: v.optional(v.boolean()),
    approval: v.optional(v.string()),
    summary: v.optional(v.string()),
    kind: v.optional(v.string()),
    repository: v.optional(v.string()),
    targetId: v.optional(v.string()),
    approvedSpec: v.optional(v.string()),
    baseCommit: v.optional(v.string()),
    deploymentMode: v.optional(v.string()),
    releaseEvidence: v.optional(v.string()),
    releaseCommit: v.optional(v.string()),
  }).index("by_issueId_and_createdAt", ["issueId", "createdAt"]),
  events: defineTable({
    runId: v.optional(v.id("runs")),
    issueId: v.optional(v.id("issues")),
    title: v.string(),
    detail: v.string(),
    kind: v.string(),
    createdAt: v.number(),
  }).index("by_createdAt", ["createdAt"]),
  settings: defineTable({ key: v.string(), value: v.string() }).index(
    "by_key",
    ["key"],
  ),
  memories: defineTable({
    owner: v.string(),
    title: v.string(),
    caption: v.string(),
    date: v.string(),
    w: v.number(),
    h: v.number(),
    seed: v.optional(v.string()),
    fileId: v.optional(v.id("_storage")),
    deleted: v.boolean(),
    createdAt: v.number(),
  }).index("by_owner", ["owner"]),
  jobs: defineTable({
    runId: v.id("runs"),
    kind: v.string(),
    status: v.string(),
    leaseUntil: v.number(),
    worker: v.optional(v.string()),
    cancel: v.boolean(),
    createdAt: v.number(),
  }).index("by_status", ["status"]),
  attachments: defineTable({
    owner: v.string(),
    caseId: v.optional(v.id("cases")),
    fileId: v.id("_storage"),
    name: v.string(),
    createdAt: v.number(),
  }).index("by_caseId", ["caseId"]),
  photoUploads: defineTable({
    owner: v.string(),
    fileId: v.id("_storage"),
    createdAt: v.number(),
  }).index("by_fileId", ["fileId"]),
  deliveries: defineTable({
    key: v.string(),
    channel: v.string(),
    destination: v.string(),
    body: v.string(),
    actor: v.string(),
    status: v.string(),
    receipt: v.optional(v.string()),
    createdAt: v.number(),
  }).index("by_key", ["key"]),
  externalEvents: defineTable({
    key: v.string(),
    messageKey: v.optional(v.string()),
    caseId: v.id("cases"),
    createdAt: v.number(),
  })
    .index("by_key", ["key"])
    .index("by_messageKey", ["messageKey"]),
  voiceSessions: defineTable({
    owner: v.string(),
    appId: v.optional(v.string()),
    customer: v.string(),
    caseId: v.optional(v.id("cases")),
    status: v.string(),
    createdAt: v.number(),
    endedAt: v.optional(v.number()),
    turnCount: v.number(),
    pendingTurn: v.optional(v.string()),
    pendingAt: v.optional(v.number()),
  }).index("by_owner_and_status", ["owner", "status"]),
  voiceTurns: defineTable({
    sessionId: v.id("voiceSessions"),
    key: v.string(),
    transcript: v.string(),
    reply: v.string(),
    createdAt: v.number(),
  }).index("by_sessionId_and_key", ["sessionId", "key"]),
});
